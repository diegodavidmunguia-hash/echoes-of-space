import { fileURLToPath } from 'node:url';
const root = fileURLToPath(new URL('../',import.meta.url));
await (async(dir)=>{
 const fs=await import('node:fs/promises'),url=await import('node:url');
 const {DatabaseSync}=await import('node:sqlite');
 const a=(await import('node:assert/strict')).default;
 const w=(await import(url.pathToFileURL(dir+'/dist/server/index.js').href)).default;
 const db=new DatabaseSync(':memory:');
 for(const n of (await fs.readdir(dir+'/drizzle')).filter(n=>n.endsWith('.sql')).sort()) db.exec(await fs.readFile(dir+'/drizzle/'+n,'utf8'));
 const DB={prepare(q){const s=db.prepare(q);return {bind(...v){return {first:()=>s.get(...v),all:()=>({results:s.all(...v)}),run:()=>s.run(...v)};}};},
 batch:async xs=>{db.exec('BEGIN');try {const r=xs.map(x=>x.run());db.exec('COMMIT');return r;}catch(e){db.exec('ROLLBACK');throw e;}}};
 const files=new Map();
 let failCleanup=false;
 const BUCKET={put:async(k,b)=>files.set(k,b),get:async k=>files.has(k)?{body:files.get(k)}:null,delete:async ks=>{if(failCleanup)throw Error('Test storage unavailable');ks.forEach(k=>files.delete(k));}};
 const origin='https://atlas.test';
 const call=(path,actor,opts={})=>w.fetch(new Request(origin+path,{...opts,headers:{origin,...(actor?{'oai-authenticated-user-id':actor,'oai-authenticated-user-email':actor+'@example.test'}:{}),...opts.headers}}),{DB,BUCKET,ATLAS_MODERATOR_EMAIL:'owner@example.test'});
 const get=async(p,role)=>(await call(p,role)).json();
 const post=(p,role,body)=>call(p,role,{method:'POST',...(body?{headers:{'content-type':'application/json'},body:JSON.stringify(body)}:{})});
 const upload=async title=>{
  const form=new FormData();
  for(const [k,v] of Object.entries({title,byline:'Autora',hardware:'Voyager 2',destination:'deep',type:'probe',category:'fiction',language:'es',format:'single'}))form.set(k,v);
  form.set('document',new Blob(['%PDF-1.7 local test']),'relato.pdf');
  form.set('cover',new Blob([await fs.readFile(dir+'/src/textures/mars.jpg')],{type:'image/jpeg'}),'cover.jpg');
  const r=await call('/api/stories','author',{method:'POST',body:form});
  const d=await r.json();
  a.equal(r.status,201,JSON.stringify(d));
  return d.story.id;
 };
 const id=await upload('Temporary original');
 const deletion='/api/stories/'+id+'/delete',doc='/api/documents/'+id,read='/api/read/'+id,cover='/api/covers/'+id;
 a.equal((await call(doc)).status,200);
 a.equal((await call(read)).headers.get('content-type'),'application/pdf');
 a.match(await (await call(doc,'reader')).text(),/^%PDF/);
 a.equal((await get('/api/stories','reader')).stories[0].canDelete,false);
 a.equal((await get('/api/stories','author')).stories[0].canDelete,true);
 a.equal((await get('/api/stories','owner')).stories[0].canDelete,true);
 a.equal((await post(deletion)).status,401);
 a.equal((await post(deletion,'reader')).status,403);
 a.equal((await call(deletion,'author',{method:'POST',headers:{origin:'https://third.test'}})).status,403);
 a.equal((await post('/api/reports/'+id,'reader',{reason:'spam',details:''})).status,201);
 const report=(await get('/api/moderation','owner')).reports[0];
 a.equal((await call('/api/moderation','author')).status,403);
 failCleanup=true;
 a.equal((await post(deletion,'author')).status,503);
 a.equal((await get('/api/stories')).stories.length,0);
 a.equal((await get('/api/stories','author')).stories[0].cleanupPending,true);
 for(const p of [doc,read,cover]) a.equal((await call(p,'owner')).status,404);
 a.equal((await post('/api/moderation','owner',{id:report.id,action:'restore'})).status,409);
 files.set('reading/'+id,new Uint8Array([1]));
 failCleanup=false;
 a.equal((await post(deletion,'author')).status,200);
 a.equal(files.size,0);
 a.equal((await post(deletion,'author')).status,200);
 a.equal((await get('/api/stories','author')).stories.length,0);
 a.equal((await get('/api/moderation?status=reviewed','owner')).reports[0].has_file,0);
 const id2=await upload('Second original');
 a.equal((await post('/api/stories/'+id2+'/delete','owner')).status,200);
 a.equal(files.size,0);
 console.log('PDF sin copia adicional y descarga pública; borrado por autor/admin; acceso denegado a terceros; ocultación, reintento y retiro de los archivos comprobados.');
})(root);
